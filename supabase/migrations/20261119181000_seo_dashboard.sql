DROP POLICY IF EXISTS seo_public_read ON public.seo_settings;
CREATE POLICY seo_public_read ON public.seo_settings FOR SELECT TO anon,authenticated USING (true);
DROP POLICY IF EXISTS seo_staff_write ON public.seo_settings;
CREATE POLICY seo_staff_write ON public.seo_settings FOR UPDATE TO authenticated
 USING ((select private.menu_role()) IN ('owner','editor'))
 WITH CHECK ((select private.menu_role()) IN ('owner','editor'));

CREATE TABLE IF NOT EXISTS public.seo_queries (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 query text NOT NULL CHECK(length(query) BETWEEN 1 AND 400),
 page text NOT NULL DEFAULT '/menu',
 start_date date NOT NULL,
 end_date date NOT NULL CHECK(end_date >= start_date),
 clicks integer NOT NULL DEFAULT 0 CHECK(clicks>=0),
 impressions integer NOT NULL DEFAULT 0 CHECK(impressions>=0),
 ctr numeric(10,6) NOT NULL DEFAULT 0 CHECK(ctr BETWEEN 0 AND 1),
 position numeric(10,3) NOT NULL DEFAULT 0 CHECK(position>=0),
 imported_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(query,page,start_date,end_date)
);
CREATE INDEX IF NOT EXISTS seo_queries_period ON public.seo_queries(end_date DESC,impressions DESC);
ALTER TABLE public.seo_queries ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.seo_queries FROM PUBLIC,anon,authenticated;
GRANT SELECT,INSERT,UPDATE,DELETE ON public.seo_queries TO authenticated;
GRANT USAGE,SELECT ON SEQUENCE public.seo_queries_id_seq TO authenticated;
DROP POLICY IF EXISTS seo_queries_owner_only ON public.seo_queries;
CREATE POLICY seo_queries_owner_only ON public.seo_queries FOR ALL TO authenticated
 USING ((select private.menu_role())='owner')
 WITH CHECK ((select private.menu_role())='owner');
